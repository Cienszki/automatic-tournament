// REPORT.md from the experiment JSON files in docs/overhaul/sim/baseline.

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ORDER } from './experiments';
import type { Table } from './experiments';

export const OUT_DIR = join(__dirname, '..', '..', '..', 'docs', 'overhaul', 'sim', 'baseline');

interface Stored { experiment: string; slug: string; seed: number; gamesPlayed: number; ms: number; command: string; tables: Table[] }

const cell = (x: string | number) => String(x).replace(/\|/g, '\\|');

export function writeReport(): void {
  if (!existsSync(OUT_DIR)) return;
  const runs = readdirSync(OUT_DIR).filter(f => f.endsWith('.json')).map(f => JSON.parse(readFileSync(join(OUT_DIR, f), 'utf8')) as Stored);
  const slugOrder = ['wiosenna', 'pdl-s2'];
  runs.sort((a, b) => ORDER.indexOf(a.experiment as never) - ORDER.indexOf(b.experiment as never) || slugOrder.indexOf(a.slug) - slugOrder.indexOf(b.slug));
  const lines: string[] = [
    '# Card game baseline measurements (WP-50)',
    '',
    'Generated by `scripts/tools/card-sim/run.ts` from the JSON files in this folder; do not edit by hand. Computer against computer, rules and AI unchanged (`src/lib/card-lab/`). Win rates are over decided games with a 95% Wilson interval in brackets; a game with no winner after 80 player turns counts as stalled. Each section names the command that reproduces it.',
    '',
  ];
  for (const r of runs) {
    lines.push(`<!-- ${r.experiment}-${r.slug} -->`);
    for (const t of r.tables) {
      lines.push(`## ${t.title}`, '', t.measured, '');
      lines.push(`| ${t.columns.map(cell).join(' | ')} |`, `|${t.columns.map(() => '---').join('|')}|`);
      for (const row of t.rows) lines.push(`| ${row.map(cell).join(' | ')} |`);
      lines.push('');
      for (const n of t.notes ?? []) lines.push(n, '');
    }
    lines.push(`Run: \`${r.command}\` (${r.gamesPlayed} games, ${(r.ms / 1000).toFixed(1)} s).`, '');
  }
  writeFileSync(join(OUT_DIR, 'REPORT.md'), lines.join('\n'));
}
